"""
Auth.js to Django REST Framework Identity Bridge.

Validates cryptographically signed, short-lived JWTs generated by Next.js
server actions / route handlers using a shared secret.

The browser never passes raw user IDs directly to Django.
Tokens must have valid signature, issuer, audience, and expiration.
"""

import jwt
import logging
from django.conf import settings
from django.contrib.auth import get_user_model
from rest_framework.authentication import BaseAuthentication
from rest_framework.exceptions import AuthenticationFailed

logger = logging.getLogger(__name__)
User = get_user_model()

class AuthJsBridgeAuthentication(BaseAuthentication):
    """
    Authenticates requests from Next.js with a signed server-to-server JWT.
    Header format: Authorization: Bearer <signed_jwt>
    """

    def authenticate_header(self, request):
        return 'Bearer realm="api"'

    def authenticate(self, request):
        auth_header = request.headers.get('Authorization')
        if not auth_header:
            return None

        parts = auth_header.split()
        if len(parts) != 2 or parts[0].lower() != 'bearer':
            return None

        token = parts[1]

        allowed_audiences = list(set([settings.INTERNAL_API_AUDIENCE, 'evermind-api', 'mediacompile-api']))
        allowed_issuers = set([settings.INTERNAL_API_ISSUER, 'evermind-web', 'mediacompile-web'])

        try:
            payload = jwt.decode(
                token,
                settings.INTERNAL_API_SECRET,
                algorithms=['HS256'],
                audience=allowed_audiences,
                options={
                    'verify_exp': True,
                    'verify_aud': True,
                    'verify_iss': False, # verified below against allowed_issuers set
                }
            )
            if payload.get('iss') not in allowed_issuers:
                raise jwt.InvalidIssuerError("Invalid token issuer.")
        except jwt.ExpiredSignatureError:
            raise AuthenticationFailed("Identity bridge token has expired.")
        except jwt.InvalidAudienceError:
            raise AuthenticationFailed("Invalid token audience.")
        except jwt.InvalidIssuerError:
            raise AuthenticationFailed("Invalid token issuer.")
        except jwt.InvalidSignatureError:
            raise AuthenticationFailed("Invalid token signature.")
        except jwt.DecodeError:
            raise AuthenticationFailed("Malformed identity token.")
        except Exception as e:
            logger.warning(f"Unexpected token validation error: {e}")
            raise AuthenticationFailed("Token authentication failed.")

        authjs_id = payload.get('sub')
        email = payload.get('email')
        name = payload.get('name', '')

        if not authjs_id or not email:
            raise AuthenticationFailed("Token missing required 'sub' or 'email' claims.")

        # Provision or retrieve mapped Django user
        user = self.get_or_create_user(authjs_id=authjs_id, email=email, name=name)
        if not user.is_active:
            raise AuthenticationFailed("User account is inactive or disabled.")

        return (user, token)

    def get_or_create_user(self, authjs_id: str, email: str, name: str = ''):
        """
        Locates or provisions the corresponding Django user for the Auth.js subject.
        Maintains stable identity mapping between Next.js and Django.
        """
        # 1. Search by primary key if authjs_id is a valid Django User UUID
        import uuid
        try:
            uid = uuid.UUID(str(authjs_id))
            user = User.objects.filter(id=uid).first()
            if user:
                if not user.authjs_id:
                    user.authjs_id = authjs_id
                    user.save(update_fields=['authjs_id'])
                return user
        except (ValueError, TypeError):
            pass

        # 2. Search by Auth.js subject ID
        user = User.objects.filter(authjs_id=authjs_id).first()
        if user:
            return user

        # 2. Search by verified email
        user = User.objects.filter(email__iexact=email).first()
        if user:
            # Link Auth.js identity to existing user account
            user.authjs_id = authjs_id
            if name and not user.name:
                user.name = name
            user.save(update_fields=['authjs_id', 'name'])
            return user

        # 3. Provision new user account
        user = User.objects.create_user(
            email=email.lower(),
            authjs_id=authjs_id,
            name=name,
            email_verified=True
        )
        return user
